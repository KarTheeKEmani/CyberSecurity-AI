"""
Mock Alert Generator Router — API controls for the security event simulator.
"""
from typing import Optional
from fastapi import APIRouter, Depends, HTTPException, Request
from sqlalchemy.orm import Session
from pydantic import BaseModel, Field
from app.core.database import get_db
from app.core.config import settings
from app.models.user import User
from app.dependencies.auth import require_role, get_current_user, get_client_ip
from app.services.alert_generator import generate_mock_alert, generate_batch, EVENT_TEMPLATES
from app.services.audit_service import log_audit_event
from app.services import auto_alert_scheduler
from app.realtime.connection_manager import manager

router = APIRouter(prefix="/alerts/generate", tags=["Mock Alert Generator"])

# Simple in-memory manual-generator state
_scheduler_state = {
    "running": False,
    "interval_seconds": settings.MOCK_GENERATOR_INTERVAL_SECONDS,
    "category": None,
    "severity": None,
    "generated_this_session": 0,
}


class GenerateRequest(BaseModel):
    category: Optional[str] = Field(None, description="Event category key, e.g. BRUTE_FORCE")
    severity: Optional[str] = Field(None, description="Override severity: LOW/MEDIUM/HIGH/CRITICAL")


class BatchRequest(BaseModel):
    count: int = Field(5, ge=1, le=20)
    category: Optional[str] = None
    severity: Optional[str] = None


class SchedulerConfigRequest(BaseModel):
    interval_seconds: int = Field(60, ge=30, le=3600)
    category: Optional[str] = None
    severity: Optional[str] = None


@router.post("/single")
async def generate_single_alert(
    req: GenerateRequest,
    request: Request,
    current_user: User = Depends(require_role(["ADMIN", "ANALYST"])),
    db: Session = Depends(get_db),
):
    """Generate one realistic SIMULATED security alert."""
    if req.category and req.category not in EVENT_TEMPLATES:
        raise HTTPException(
            status_code=400,
            detail=f"Unknown category '{req.category}'. Valid: {list(EVENT_TEMPLATES.keys())}"
        )

    incident = generate_mock_alert(
        db=db,
        category=req.category,
        severity=req.severity,
        created_by=current_user.email,
    )
    _scheduler_state["generated_this_session"] += 1

    log_audit_event(
        db=db,
        action="MOCK_ALERT_GENERATED",
        resource="INCIDENT",
        resource_id=incident.public_id,
        user=current_user,
        detail=f"Simulated alert {incident.public_id} generated by {current_user.email} (cat={req.category}, sev={req.severity})",
        severity="info",
        ip_address=get_client_ip(request),
    )

    await manager.broadcast("incident.created", {
        "id": incident.id,
        "public_id": incident.public_id,
        "title": incident.title,
        "severity": incident.severity,
        "status": incident.status,
        "source": incident.source,
        "assignee": incident.assignee,
        "is_simulated": True,
        "created_at": incident.created_at.isoformat(),
    })

    return {
        "status": "created",
        "incident": {
            "id": incident.id,
            "public_id": incident.public_id,
            "title": incident.title,
            "severity": incident.severity,
            "status": incident.status,
            "is_simulated": True,
        },
        "generated_this_session": _scheduler_state["generated_this_session"],
    }


@router.post("/batch")
async def generate_batch_alerts(
    req: BatchRequest,
    request: Request,
    current_user: User = Depends(require_role(["ADMIN"])),
    db: Session = Depends(get_db),
):
    """Generate a controlled batch of SIMULATED alerts (max 20, admin only)."""
    incidents = generate_batch(db, count=req.count, category=req.category, severity=req.severity)
    _scheduler_state["generated_this_session"] += len(incidents)

    log_audit_event(
        db=db,
        action="MOCK_ALERT_BATCH_GENERATED",
        resource="INCIDENT",
        resource_id=f"batch-{len(incidents)}",
        user=current_user,
        detail=f"Batch of {len(incidents)} simulated alerts generated by {current_user.email}",
        severity="info",
        ip_address=get_client_ip(request),
    )

    for inc in incidents:
        await manager.broadcast("incident.created", {
            "id": inc.id,
            "public_id": inc.public_id,
            "title": inc.title,
            "severity": inc.severity,
            "status": inc.status,
            "is_simulated": True,
            "created_at": inc.created_at.isoformat(),
        })

    return {
        "status": "created",
        "count": len(incidents),
        "incidents": [
            {"id": i.id, "public_id": i.public_id, "severity": i.severity}
            for i in incidents
        ],
        "generated_this_session": _scheduler_state["generated_this_session"],
    }


@router.get("/categories")
def list_categories(current_user: User = Depends(get_current_user)):
    """List available event categories for mock generation."""
    return {
        "categories": [
            {"key": k, "severity": v["severity"], "category": v["category"]}
            for k, v in EVENT_TEMPLATES.items()
        ]
    }


@router.get("/status")
def get_generator_status(current_user: User = Depends(get_current_user)):
    """Get current mock generator state (manual + auto-scheduler)."""
    return {
        "scheduler_running": _scheduler_state["running"],
        "interval_seconds": _scheduler_state["interval_seconds"],
        "category_filter": _scheduler_state["category"],
        "severity_filter": _scheduler_state["severity"],
        "generated_this_session": _scheduler_state["generated_this_session"],
        "demo_mode": settings.DEMO_MODE,
        "auto_scheduler": auto_alert_scheduler.get_state(),
    }


@router.get("/scheduler/status")
def get_auto_scheduler_status(current_user: User = Depends(get_current_user)):
    """Get the auto-alert scheduler state (fires every AUTO_ALERT_INTERVAL_SECONDS)."""
    return auto_alert_scheduler.get_state()


@router.post("/scheduler/start")
def start_auto_scheduler(current_user: User = Depends(require_role(["ADMIN"]))):
    """Manually start the auto-alert scheduler (admin only)."""
    auto_alert_scheduler.start_scheduler()
    return {"status": "started", **auto_alert_scheduler.get_state()}


@router.post("/scheduler/stop")
def stop_auto_scheduler(current_user: User = Depends(require_role(["ADMIN"]))):
    """Manually stop the auto-alert scheduler (admin only)."""
    auto_alert_scheduler.stop_scheduler()
    return {"status": "stopped", **auto_alert_scheduler.get_state()}

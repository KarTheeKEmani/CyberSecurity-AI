"""
API Keys Management Router (Hashed Storage & Scoped Permissions)
"""
from typing import List
from datetime import datetime, timezone
import uuid
from fastapi import APIRouter, Depends, HTTPException, status, Request
from sqlalchemy.orm import Session
from app.core.database import get_db
from app.core.security import generate_api_key
from app.models.api_key import ApiKey
from app.models.user import User
from app.schemas.analytics import ApiKeyResponse, ApiKeyCreatedResponse, ApiKeyCreate
from app.dependencies.auth import get_current_user, require_role, get_client_ip
from app.services.audit_service import log_audit_event

router = APIRouter(prefix="/api-keys", tags=["API Keys"])


@router.get("", response_model=List[ApiKeyResponse])
def list_api_keys(
    current_user: User = Depends(require_role(["ADMIN", "ANALYST"])),
    db: Session = Depends(get_db),
):
    """List all API keys (stored securely with hashed values)."""
    return db.query(ApiKey).order_by(ApiKey.created_at.desc()).all()


@router.post("", response_model=ApiKeyCreatedResponse, status_code=status.HTTP_201_CREATED)
def create_api_key(
    req: ApiKeyCreate,
    request: Request,
    current_user: User = Depends(require_role(["ADMIN"])),
    db: Session = Depends(get_db),
):
    """
    Generate a new scoped API key.
    The raw plaintext key is returned ONCE in this response and NEVER stored or shown again.
    """
    raw_key, key_prefix_display, key_hash = generate_api_key()
    public_id = f"KEY-{uuid.uuid4().hex[:8].upper()}"

    key_record = ApiKey(
        public_id=public_id,
        name=req.name,
        owner_id=current_user.id,
        created_by_name=current_user.full_name or current_user.email,
        key_prefix=key_prefix_display,
        key_hash=key_hash,
        permissions=req.permissions or ["incidents:read"],
        status="active",
        created_at=datetime.now(timezone.utc),
    )
    db.add(key_record)
    db.commit()
    db.refresh(key_record)

    log_audit_event(
        db=db,
        action="API_KEY_CREATED",
        resource="API_KEY",
        resource_id=key_record.public_id,
        user=current_user,
        detail=f"API key '{req.name}' generated by {current_user.email} with permissions: {req.permissions}",
        new_value={"public_id": key_record.public_id, "name": req.name, "permissions": req.permissions},
        severity="warning",
        ip_address=get_client_ip(request),
    )

    return {
        "id": key_record.id,
        "public_id": key_record.public_id,
        "name": key_record.name,
        "created_by_name": key_record.created_by_name,
        "key_prefix": key_record.key_prefix,
        "permissions": key_record.permissions,
        "status": key_record.status,
        "request_count": key_record.request_count,
        "created_at": key_record.created_at,
        "last_used_at": key_record.last_used_at,
        "raw_key": raw_key,
    }


@router.delete("/{id}", status_code=status.HTTP_200_OK)
def revoke_api_key(
    id: int,
    request: Request,
    current_user: User = Depends(require_role(["ADMIN"])),
    db: Session = Depends(get_db),
):
    """Revoke an existing API key."""
    key_record = db.query(ApiKey).filter(ApiKey.id == id).first()
    if not key_record:
        raise HTTPException(status_code=404, detail="API key not found")

    key_record.status = "revoked"
    db.commit()

    log_audit_event(
        db=db,
        action="API_KEY_REVOKED",
        resource="API_KEY",
        resource_id=key_record.public_id,
        user=current_user,
        detail=f"API key '{key_record.name}' ({key_record.public_id}) revoked by {current_user.email}",
        old_value={"status": "active"},
        new_value={"status": "revoked"},
        severity="warning",
        ip_address=get_client_ip(request),
    )

    return {"status": "success", "message": f"API key {key_record.public_id} revoked"}
